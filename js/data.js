// найти сериал по id
function byId(id) {
  return SERIES.filter(function (s) { return s.id === id; })[0];
}

// 7 -> "07"
function num(id) {
  return (id < 10 ? '0' : '') + id;
}

// 1 сериал, 2 сериала, 5 сериалов
function plural(n) {
  var last = n % 10, last2 = n % 100;
  if (last === 1 && last2 !== 11) return n + ' сериал';
  if (last >= 2 && last <= 4 && (last2 < 10 || last2 >= 20)) return n + ' сериала';
  return n + ' сериалов';
}

// чтение и запись в localStorage (в try, потому что в некоторых браузерах он может быть выключен)
function load(key, def) {
  try {
    var v = JSON.parse(localStorage.getItem(key));
    return v === null ? def : v;
  } catch (e) {
    return def;
  }
}
function save(key, value) {
  try { localStorage.setItem(key, JSON.stringify(value)); } catch (e) {}
}
